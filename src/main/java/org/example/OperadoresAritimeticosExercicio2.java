package org.example;

public class OperadoresAritimeticosExercicio2 {
    public static void main(String[] args) {
        //  esta atividade esta sendo o exercio parte dois da atividade operadores //
        int num1 = 10 ;
        int num2 = 3 ;

        System.out.println("Soma: "+ (num1 + num2));
        System.out.println("Subtracao: "+ (num1 - num2));
        System.out.println("Multipicador: "+ (num1 * num2));
        System.out.println("Divisao: "+(num1 / num2));
        System.out.println("Resto: "+ (num1 % num2));

        
    }
}
