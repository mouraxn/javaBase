package org.example;

public class Aula03_Condicionais {
     public static void main (String[] args){

         int nota  = 10;

         if (nota >= 10 ){
                 System.out.println(" aprovado!!");
         }else if (nota <= 6){
             System.out.println("passa mas com cuidado  ");
         }else {
             System.out.println("nao passa !!!");
         }

     }
}
