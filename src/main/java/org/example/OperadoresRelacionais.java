package org.example;

public class OperadoresRelacionais {
    public static void main(String[] args) {
        int idade = 18;
        System.out.println("Maior ou igual a 18: " + (idade >= 18));
        System.out.println("Igual a 18: " + (idade == 18));
        System.out.println("Diferente de 20: " + (idade != 20));
    }
}
